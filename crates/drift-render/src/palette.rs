/// Canvas colours, as sRGB bytes (unmultiplied alpha).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Palette {
    pub background: [u8; 4],
    pub grid_minor: [u8; 4],
    pub grid_major: [u8; 4],
    pub axis_x: [u8; 4],
    pub axis_y: [u8; 4],
    pub solid: [u8; 4],
    pub construction: [u8; 4],
    pub center: [u8; 4],
    pub point: [u8; 4],
}

impl Palette {
    pub fn dark() -> Self {
        Self {
            background: [0x1b, 0x1d, 0x21, 0xff],
            grid_minor: [0x26, 0x29, 0x2e, 0xff],
            grid_major: [0x31, 0x35, 0x3b, 0xff],
            axis_x: [0xc2, 0x4a, 0x4a, 0xb0],
            axis_y: [0x4a, 0xa8, 0x5c, 0xb0],
            solid: [0xe6, 0xe8, 0xeb, 0xff],
            construction: [0x6f, 0xa8, 0xdc, 0xff],
            center: [0xa0, 0xa6, 0xad, 0xff],
            point: [0xf2, 0xb5, 0x3c, 0xff],
        }
    }

    pub fn light() -> Self {
        Self {
            background: [0xfb, 0xfb, 0xfa, 0xff],
            grid_minor: [0xee, 0xef, 0xf0, 0xff],
            grid_major: [0xdc, 0xde, 0xe1, 0xff],
            axis_x: [0xd0, 0x3a, 0x3a, 0x90],
            axis_y: [0x2e, 0x9a, 0x48, 0x90],
            solid: [0x1d, 0x21, 0x26, 0xff],
            construction: [0x2f, 0x6f, 0xb3, 0xff],
            center: [0x5c, 0x63, 0x6b, 0xff],
            point: [0xc7, 0x7a, 0x00, 0xff],
        }
    }
}
